/*
 * STM32F407 板级 PWM 通道编号。
 *
 * TIM3当前由右编码器独占；TIM2四个通道用于双路AT8236电机驱动；
 * TIM1映射保留为后端候选能力。通道编号只用于 Platform MCU 与 Board 层，
 * 不应泄漏到应用层。
 */
