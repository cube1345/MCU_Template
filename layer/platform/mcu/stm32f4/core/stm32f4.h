#define STM32F4_PWM_TIM1_CH1 INT32_C(1)
#define STM32F4_PWM_TIM1_CH2 INT32_C(2)
#define STM32F4_PWM_TIM1_CH3 INT32_C(3)
#define STM32F4_PWM_TIM1_CH4 INT32_C(4)
#define STM32F4_PWM_TIM2_CH1 INT32_C(5)
#define STM32F4_PWM_TIM2_CH2 INT32_C(6)
#define STM32F4_PWM_TIM2_CH3 INT32_C(7)
#define STM32F4_PWM_TIM2_CH4 INT32_C(8)

